SELECT s.id, s.paid_amount,
  CONCAT(s.start_date, ' 10:00:00'),
  CASE (s.id % 3)
    WHEN 0 THEN 'cash'
    WHEN 1 THEN 'card'
    ELSE 'transfer'
  END,
  1
